def table(path):
    rows = list(csv.DictReader(io.StringIO(path.read_text(encoding="utf-8-sig"))))[2:]
    return {int(row["ID"]): row for row in rows if row.get("ID")}


def wire(data):
    offset = 0

    def varint():
        nonlocal offset
        value = 0
        for shift in range(0, 70, 7):
            if offset >= len(data):
                raise ValueError("Truncated protobuf varint")
            byte = data[offset]
            offset += 1
            value |= (byte & 127) << shift
            if byte < 128:
                return value
        raise ValueError("Invalid protobuf varint")

    fields = []
    while offset < len(data):
        tag = varint()
        number, kind = tag >> 3, tag & 7
        if number <= 0:
            raise ValueError("Invalid protobuf tag")
        if kind == 0:
            value = varint()
        else:
            size = varint() if kind == 2 else 8 if kind == 1 else 4 if kind == 5 else -1
            if size < 0 or offset + size > len(data):
                raise ValueError("Invalid protobuf field length")
            value = data[offset:offset + size]
            offset += size
        fields.append((number, kind, value))
    return fields


def number(fields, key):
    return next((value for field, kind, value in fields if field == key and kind == 0), 0)


