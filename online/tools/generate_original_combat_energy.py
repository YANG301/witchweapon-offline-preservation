def generate(args):
    seed = json.loads(args.seed.read_text(encoding="utf-8-sig"))
    catalog = seed["_catalog"]
    servant_ids = sorted(map(int, catalog["servants"]))
    if len(servant_ids) != 41:
        raise ValueError("Expected the 41 restored owned-servant templates")
    servants = table(args.original / "servant.txt")
    ranks = table(args.original / "servantrankinfo.txt")
    equips = table(args.original / "servantequip.txt")
    # Native UI formula adds equipment values after dividing the rank by 10000.
    # These preserved 2020 equips contain no energy attributes, so no missing
    # equipment term may silently be guessed or discarded.
    for row in equips.values():
        for slot in range(1, 6):
            if row.get("attribute_type" + str(slot)) in ("99", "100", "101", "102"):
                raise ValueError("Energy equipment requires a separately audited transport formula")

    energy_rows = []
    rank_count = 0
    for sid in servant_ids:
        base = int(servants[sid]["rank_info"])
        expected_ranks = sorted(map(int, catalog["ranks"][str(sid)]))
        if expected_ranks != list(range(1, 11)):
            raise ValueError(f"Unexpected catalog rank coverage for servant {sid}")
        for rank in expected_ranks:
            row = ranks[base * 100 + rank]
            if int(row["rank"]) != rank:
                raise ValueError("Original rank identity mismatch")
            energy = tuple(int(row[column]) for column in ENERGY_COLUMNS)
            if any(value < 0 or value > 2147483647 for value in energy):
                raise ValueError("Energy outside protobuf int32 range")
            rank_count += 1
            if (energy_rows and energy_rows[-1][0] == sid
                    and energy_rows[-1][2] == rank - 1
                    and tuple(energy_rows[-1][3:]) == energy):
                energy_rows[-1][2] = rank
            else:
                energy_rows.append([sid, rank, rank, *energy])

    evidence = json.loads(args.effects.read_text(encoding="utf-8-sig"))
    effect_rows = evidence["rows"]
    if len(effect_rows) != 95 or len({r["spellID"] for r in effect_rows}) != 95:
        raise ValueError("Expected the 95 audited distinct weapon effects")
    if len({r["triggerID"] for r in effect_rows}) != 95:
        raise ValueError("Audited weapon trigger IDs must be unique")
    effects = [[r["servantID"], r["weaponID"], r["spellID"], r["triggerID"],
                *sorted(set(r["directBuffIDArgs"]))] for r in effect_rows]
    effects.sort()
    role = wire(base64.b64decode(seed["/combat/role/info"]["base64"]))
    unit = wire(next(v for n, t, v in role if n == 102 and t == 2))
    unit_ids = {field: {number(wire(v), key) for n, t, v in unit if n == field and t == 2}
                for field, key in ((1, 2), (4, 2), (2, 3))}
    for effect in effects:
        if effect[0] not in servant_ids or str(effect[1]) not in catalog["weapons"]:
            raise ValueError("Weapon link outside restored catalog")
        if effect[2] not in unit_ids[1] or effect[3] not in unit_ids[4]:
            raise ValueError("Audited spell or trigger absent from fixture")
        if not set(effect[4:]).issubset(unit_ids[2]):
            raise ValueError("Audited direct buff absent from fixture")

    sources = [args.original / name for name in ("servant.txt", "servantrankinfo.txt", "servantequip.txt")]
    hashes = "\n".join("    // " + path.name + " " + hashlib.sha256(path.read_bytes()).hexdigest()
                       for path in sources)
    # Explanatory native evidence can be added to the audit without changing
    # generated source; bind only the exact stable links consumed at runtime.
    link_bytes = json.dumps(effects, ensure_ascii=True, separators=(",", ":")).encode("ascii")
    hashes += "\n    // Audited weapon links " + hashlib.sha256(link_bytes).hexdigest()
    java_rows = lambda rows: "\n".join("        {" + ",".join(str(value) + "L" for value in row) + "},"
                                      for row in rows)
    output = (JAVA.replace("%HASHES%", hashes).replace("%ENERGY%", java_rows(energy_rows))
              .replace("%EFFECTS%", java_rows(effects))).encode("utf-8")
    if args.check:
        if args.output.read_bytes() != output:
            raise ValueError("OriginalCombatRules.java differs from regenerated original inputs")
    else:
        args.output.write_bytes(output)
    print(json.dumps({"servants": len(servant_ids), "originalRankRows": rank_count,
                      "compressedEnergyRows": len(energy_rows), "weaponEffectRows": len(effects),
                      "directBuffIDs": len({buff for row in effects for buff in row[4:]}),
                      "javaSHA256": hashlib.sha256(output).hexdigest(), "checkOnly": args.check},
                     ensure_ascii=False))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--original", type=Path, default=ORIGINAL)
    parser.add_argument("--seed", type=Path, default=PROJECT / "构建/战斗修复/offline_responses.json")
    parser.add_argument("--effects", type=Path, default=PROJECT / "验收/战斗全面核查/95条武器被动等级接入断言.json")
    parser.add_argument("--output", type=Path,
                        default=PROJECT / "legacy-server/src/com/codex/witchweapon/OriginalCombatRules.java")
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args())


if __name__ == "__main__":
    main()
